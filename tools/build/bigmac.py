"""The Economist's Big Mac index, 2000-2026 (data CC BY 4.0, code MIT).
Repository: https://github.com/TheEconomist/big-mac-data  (README, "Licence": "The data generated by The Economist are
available under the Creative Commons Attribution 4.0 International License.")
Fetch:  mkdir -p .cache/bigmac && curl -sSfo .cache/bigmac/full.csv \
  https://raw.githubusercontent.com/TheEconomist/big-mac-data/master/output-data/big-mac-full-index.csv
Run:    python3 tools/build/bigmac.py
Output: data/economics/bigmac.json  series {price_usd, rel_us, rel_us_adj} by year (one mid-year survey per year),
        sets {valuation} for the latest survey.
Only Economist-generated columns are shipped (Big Mac price in dollars and the index); the third-party inputs
(exchange rates from Refinitiv, GDP per person from the IMF) are left out. The euro-area figure (EUZ) is shown on
every country that used the euro in that year, which is an Orbis simplification: it is one weighted average."""
import os, csv, json, datetime
root = os.path.join(os.path.dirname(__file__), "..", "..")
CSV = os.path.join(root, ".cache/bigmac/full.csv")
OUT = os.path.join(root, "data/economics/bigmac.json")
EURO = {"AUT": 1999, "BEL": 1999, "FIN": 1999, "FRA": 1999, "DEU": 1999, "IRL": 1999, "ITA": 1999, "LUX": 1999,
        "NLD": 1999, "PRT": 1999, "ESP": 1999, "GRC": 2001, "SVN": 2007, "CYP": 2008, "MLT": 2008, "SVK": 2009,
        "EST": 2011, "LVA": 2014, "LTU": 2015, "HRV": 2023, "BGR": 2026}
rows = list(csv.DictReader(open(CSV)))
# one survey per year: the mid-year one (April-July; the January surveys from 2006 on are skipped)
by_year = {}
for r in rows:
    y, m = int(r["date"][:4]), int(r["date"][5:7])
    if m >= 4:
        by_year.setdefault(y, set()).add(r["date"])
dates = {y: max(ds) for y, ds in by_year.items()}
years = sorted(dates)
pick = {d: y for y, d in dates.items()}
series = {"price_usd": {}, "rel_us": {}, "rel_us_adj": {}}
def put(key, iso, y, v):
    series[key].setdefault(iso, [None] * len(years))[years.index(y)] = v
for r in rows:
    y = pick.get(r["date"])
    if y is None:
        continue
    isos = [r["iso_a3"]] if r["iso_a3"] != "EUZ" else [k for k, j in EURO.items() if j <= y]
    for iso in isos:
        put("price_usd", iso, y, round(float(r["dollar_price"]), 2))
        put("rel_us", iso, y, round(100 * (1 + float(r["USD_raw"])), 1))
        if r["USD_adjusted"]:
            put("rel_us_adj", iso, y, round(100 * (1 + float(r["USD_adjusted"])), 1))
last = years[-1]; li = years.index(last)
def band(v):
    if v >= 110: return "over"
    if v > 90: return "near"
    if v > 60: return "under"
    return "deep"
valuation = {k: band(v[li]) for k, v in series["rel_us"].items() if v[li] is not None}
out = {
    "source": "economist-bigmac", "asOf": dates[last], "retrieved": datetime.date.today().isoformat(),
    "note": "The Economist, Big Mac index (github.com/TheEconomist/big-mac-data), CC BY 4.0. One survey per year: "
            "the mid-year survey (dates: " + ", ".join(dates[y] for y in years) + "). Prices converted to US dollars "
            "at market exchange rates by The Economist. rel_us = Big Mac price as % of the US price (100 + raw index); "
            "rel_us_adj = same, adjusted for GDP per person (The Economist's adjusted index). Euro-area average shown on "
            "every euro member for that year (Orbis simplification).",
    "years": years,
    "series": {
        "price_usd": {"label": "Price of a Big Mac in US dollars", "units": "US dollars", "values": series["price_usd"]},
        "rel_us": {"label": "Big Mac price as % of the US price (raw index)", "units": "% of US price", "values": series["rel_us"]},
        "rel_us_adj": {"label": "Big Mac price as % of the US price, adjusted for GDP per person", "units": "% of US price", "values": series["rel_us_adj"]},
    },
    "sets": {"valuation": {"label": "Currency against the dollar, " + dates[last], "values": valuation,
        "labels": {"over": "Overvalued by 10% or more", "near": "Within 10%", "under": "Undervalued by 10–40%", "deep": "Undervalued by 40% or more"}}},
}
os.makedirs(os.path.dirname(OUT), exist_ok=True)
json.dump(out, open(OUT, "w"), separators=(",", ":"))
print(OUT, os.path.getsize(OUT) // 1024, "KB,", len(years), "years,", len(series["price_usd"]), "countries; latest", dates[last])
